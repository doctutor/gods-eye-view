/**
 * The review of a match run (data/cottereau/review.md): the tracks with no
 * match or a weak one, the pairs that differ by definition (differences.mjs),
 * the large Cliopatria polities alive and in view
 * that the video never names (what Cottereau cut), and per century the
 * video's labels against Cliopatria's polities.
 *
 * Personal fork tooling; not part of upstream God's Eye View.
 */

import { DIFFERENCES } from './differences.mjs';
import { framingAt, framingExtent } from './framings.mjs';

const fmtYear = (y) => (y < 0 ? `${-y} BC` : `${y}`);
const number = (n) => Number(n).toLocaleString('en-US');

/** A century's label: -2500 → "26th c. BC" style by its first year. */
function centuryOf(year) {
  return year < 0 ? -Math.ceil(-year / 100) : Math.floor(year / 100) + 1;
}
const centuryLabel = (c) => (c < 0 ? `${-c} c. BC` : `${c} c.`);

/** Whether a record's box centre is in the view of the framing shown in `year`. */
function inView(record, framings, frames, year) {
  const frame = frames.find((f) => f.year >= year) || frames.at(-1);
  const framing = framingAt(framings, frame.t);
  if (!framing) return false;
  const e = framing.extent || framingExtent(framing);
  const lon = (record.box.west + record.box.east) / 2;
  const lat = (record.box.south + record.box.north) / 2;
  return lon >= e.west && lon <= e.east && lat >= e.south && lat <= e.north;
}

export function buildReview({
  tracks,
  matches,
  records,
  framings,
  frames,
  largeKm2 = 500_000,
  minYears = 50,
}) {
  const firstYear = frames[0].year;
  const lastYear = frames.at(-1).year;
  const steady = tracks
    .map((t, i) => ({ track: t, match: matches[i] }))
    .filter(({ track }) => track.samples >= 3);
  const matched = steady.filter(({ match }) => match.name);
  const byConfidence = { high: 0, medium: 0, low: 0 };
  const byReason = {};
  for (const { match } of matched) {
    byConfidence[match.confidence] += 1;
    byReason[match.reason] = (byReason[match.reason] || 0) + 1;
  }
  const lines = [];
  lines.push('# Cottereau against Cliopatria: review');
  lines.push('');
  lines.push(
    `Labels of Cottereau's "History of the World: Every Year" read at one sample a second, ${number(frames.length)} samples from ${fmtYear(firstYear)} to ${fmtYear(lastYear)}; matched to Cliopatria v0.2.1 (CC BY 4.0). Generated by \`node scripts/cottereau/index.mjs build\`.`,
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(
    `- Tracks seen in three samples or more: ${number(steady.length)} (of ${number(tracks.length)} seen twice or more).`,
  );
  lines.push(
    `- Matched: ${number(matched.length)} (${((100 * matched.length) / Math.max(1, steady.length)).toFixed(1)}%): ${byConfidence.high} high, ${byConfidence.medium} medium, ${byConfidence.low} low confidence. Matched by name or abbreviation (high and medium): ${number(byConfidence.high + byConfidence.medium)} (${((100 * (byConfidence.high + byConfidence.medium)) / Math.max(1, steady.length)).toFixed(1)}%); low is a guess by place alone, often a polity Cottereau shows inside one Cliopatria has.`,
  );
  lines.push(
    `- By reason: ${Object.entries(byReason)
      .map(([r, n]) => `${r} ${n}`)
      .join(', ')}.`,
  );
  lines.push('');
  // Weak or none.
  const weak = steady.filter(
    ({ match }) => !match.name || match.confidence === 'low',
  );
  lines.push(`## Tracks with no match or a weak one (${weak.length})`);
  lines.push('');
  lines.push(
    '| Label | Years | Samples | Lon, lat | Match | Why | Nearest candidates |',
  );
  lines.push('| --- | --- | ---: | --- | --- | --- | --- |');
  for (const { track, match } of weak.sort(
    (a, b) => a.track.firstYear - b.track.firstYear,
  )) {
    const alternatives = (match.alternatives || [])
      .map((a) => `${a.name} (${a.distanceKm} km)`)
      .join('; ');
    const refused = match.refused?.length
      ? `; refused far: ${match.refused.map((r) => `${r.name} ${number(r.distanceKm)} km`).join(', ')}`
      : '';
    lines.push(
      `| ${track.text.replace(/\|/g, '/')} | ${fmtYear(track.firstYear)}–${fmtYear(track.lastYear)} | ${track.samples} | ${track.lon.toFixed(1)}, ${track.lat.toFixed(1)} | ${match.name || '—'} | ${match.reason}${refused} | ${alternatives} |`,
    );
  }
  lines.push('');
  // Pairs that differ by definition, not by error.
  lines.push(`## Pairs that differ by definition (${DIFFERENCES.length})`);
  lines.push('');
  lines.push(
    "Matched rightly, but Cottereau and Cliopatria draw different things under the name; checked by hand against the frames and Cliopatria's records (`differences.mjs`). The borders' quality report keeps them apart from its IoU summary.",
  );
  lines.push('');
  lines.push('| Label | Cliopatria | Years | What differs |');
  lines.push('| --- | --- | --- | --- |');
  for (const d of DIFFERENCES)
    lines.push(
      `| ${d.label} | ${d.cliopatria} | ${fmtYear(d.from)}–${fmtYear(d.to)} | ${d.why.replace(/\|/g, '/')} |`,
    );
  lines.push('');
  // Large polities absent from the video.
  // Named: a track's match, or a name or abbreviation it took in one of its periods.
  const named = new Set(matched.map(({ match }) => match.name));
  // A continued period (the label going on over a renamed polity) counts
  // when it lasts: 50 years, or a quarter of its track's span (not a flicker).
  for (const { track, match } of steady)
    for (const period of match.periods || []) {
      if (!period.name || period.reason === 'place' || period.reason === 'none')
        continue;
      const years = period.to - period.from + 1;
      if (
        period.reason === 'continued' &&
        years < 50 &&
        years < 0.25 * (track.lastYear - track.firstYear + 1)
      )
        continue;
      named.add(period.name);
    }
  // A polity and its bracketed twin (it with its dependencies) are one.
  for (const name of [...named]) named.add(name.replace(/^\((.*)\)$/, '$1'));
  // Cliopatria's names in brackets are wholes (a colonial empire, an
  // alliance, a period): not one polity a map labels.
  const aggregate = (name) => /^\(/.test(name);
  const polities = new Map();
  for (const r of records) {
    if (
      r.type !== 'POLITY' ||
      aggregate(r.name) ||
      r.to < firstYear ||
      r.from > lastYear
    )
      continue;
    let p = polities.get(r.name);
    if (!p)
      polities.set(
        r.name,
        (p = {
          name: r.name,
          from: r.from,
          to: r.to,
          area: 0,
          wikipedia: r.wikipedia,
          records: [],
        }),
      );
    p.from = Math.min(p.from, r.from);
    p.to = Math.max(p.to, r.to);
    p.area = Math.max(p.area, r.area);
    p.records.push(r);
  }
  const absent = [...polities.values()]
    .filter(
      (p) =>
        !named.has(p.name) &&
        p.area >= largeKm2 &&
        Math.min(p.to, lastYear) - Math.max(p.from, firstYear) + 1 >=
          minYears &&
        p.records.some((r) =>
          inView(r, framings, frames, Math.max(r.from, firstYear)),
        ),
    )
    .sort((a, b) => b.area - a.area);
  lines.push(
    `## Large Cliopatria polities in view that the video never names (${absent.length})`,
  );
  lines.push('');
  lines.push(
    `Polities of at least ${number(largeKm2)} km² at their largest, alive ${minYears} years or more of the span read, whose box centre was inside the map's view, and named by no track (by its match, or by name or abbreviation in one of its periods): what Cottereau left out or drew under another name (or what the OCR missed). Cliopatria's bracketed wholes (colonial empires, alliances) are left out.`,
  );
  lines.push('');
  lines.push('| Polity | Years | Largest area (km²) | Wikipedia |');
  lines.push('| --- | --- | ---: | --- |');
  for (const p of absent)
    lines.push(
      `| ${p.name} | ${fmtYear(p.from)}–${fmtYear(p.to)} | ${number(Math.round(p.area))} | ${p.wikipedia || ''} |`,
    );
  lines.push('');
  // Per century.
  lines.push('## Per century');
  lines.push('');
  lines.push(
    '| Century | Video labels | Cliopatria polities they name | Cliopatria polities alive, in view | Share named |',
  );
  lines.push('| --- | ---: | ---: | ---: | ---: |');
  for (let c = centuryOf(firstYear); c <= centuryOf(lastYear); c++) {
    if (c === 0) continue;
    const start = c < 0 ? c * 100 : (c - 1) * 100 + 1;
    const end = c < 0 ? c * 100 + 99 : c * 100;
    const labels = steady.filter(
      ({ track }) => track.firstYear <= end && track.lastYear >= start,
    );
    // The polities the labels name in this century: their periods' names
    // (by name, abbreviation, or continued), less brackets.
    const names = new Set();
    for (const { match } of labels)
      for (const period of match.periods || [])
        if (
          period.name &&
          period.reason !== 'place' &&
          period.reason !== 'none' &&
          period.from <= end &&
          period.to >= start
        )
          names.add(period.name.replace(/^\((.*)\)$/, '$1'));
    const alive = [...polities.values()].filter((p) =>
      p.records.some(
        (r) =>
          r.from <= end &&
          r.to >= start &&
          inView(r, framings, frames, Math.max(start, r.from, firstYear)),
      ),
    );
    lines.push(
      `| ${centuryLabel(c)} | ${labels.length} | ${names.size} | ${alive.length} | ${alive.length ? ((100 * [...names].filter((n) => alive.some((p) => p.name === n)).length) / alive.length).toFixed(0) : 0}% |`,
    );
  }
  lines.push('');
  return {
    markdown: `${lines.join('\n')}\n`,
    summary: `${steady.length} steady tracks, ${matched.length} matched (${((100 * matched.length) / Math.max(1, steady.length)).toFixed(1)}%: ${byConfidence.high} high, ${byConfidence.medium} medium, ${byConfidence.low} low; high or medium ${((100 * (byConfidence.high + byConfidence.medium)) / Math.max(1, steady.length)).toFixed(1)}%); ${weak.length} weak or unmatched; ${absent.length} large polities absent`,
    weak: weak.length,
    absent: absent.length,
    matched: matched.length,
    steady: steady.length,
  };
}
